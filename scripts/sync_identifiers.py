#!/usr/bin/env python3
"""Keep the project's DOI, ORCID, repository URL and version consistent everywhere.

``identifiers.json`` (plus ``apgi_framework/__version__.py`` for version and release
date) is the single source of truth. This script

* writes the generated identifier block into README.md and the matching fields of
  CITATION.cff (``--write``);
* verifies both are in sync and then scans every tracked text file for DOIs, ORCID
  iDs, repository URLs and versions that diverge from the source (``--check``,
  the default). Exit status 1 means drift; each finding names file and line.

Only the standard library and PyYAML are needed.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Dict, Iterable, List, Optional

import yaml

ROOT = Path(__file__).resolve().parent.parent
BEGIN = "<!-- identifiers:begin (generated by scripts/sync_identifiers.py; do not edit by hand) -->"
END = "<!-- identifiers:end -->"
TEXT_SUFFIXES = {
    ".md",
    ".py",
    ".cff",
    ".toml",
    ".yml",
    ".yaml",
    ".json",
    ".txt",
    ".cfg",
    ".rst",
    ".ini",
}
MAX_BYTES = 2_000_000

DOI_RE = re.compile(r"10\.5281/zenodo\.\d+")
ORCID_RE = re.compile(r"(?<![\d-])\d{4}-\d{4}-\d{4}-\d{3}[\dX](?![\d-])")
REPO_RE = re.compile(r"github\.com/([A-Za-z0-9_.-]+)/(apgi[A-Za-z0-9_.-]*)")


@dataclass(frozen=True)
class Finding:
    path: str
    line: int
    message: str

    def __str__(self) -> str:
        return f"{self.path}:{self.line}: {self.message}"


# -- source of truth ---------------------------------------------------------
def load_identifiers(root: Path = ROOT) -> Dict[str, Any]:
    data: Dict[str, Any] = json.loads((root / "identifiers.json").read_text(encoding="utf-8"))
    ns: Dict[str, Any] = {}
    exec((root / "apgi_framework" / "__version__.py").read_text(encoding="utf-8"), ns)  # noqa: S102
    data["version"] = ns["__version__"]
    data["date_released"] = ns["__release_date__"]
    if not orcid_checksum_ok(data["author"]["orcid"]):
        raise ValueError(f"ORCID {data['author']['orcid']} fails its ISO 7064 check digit")
    return data


def orcid_checksum_ok(orcid: str) -> bool:
    digits = orcid.replace("-", "")
    if len(digits) != 16:
        return False
    total = 0
    for ch in digits[:15]:
        total = (total + int(ch)) * 2
    check = (12 - total % 11) % 11
    return digits[15] == ("X" if check == 10 else str(check))


# -- README ------------------------------------------------------------------
def render_readme_block(ids: Dict[str, Any]) -> str:
    author = ids["author"]
    key = f"{author['family_names'].lower()}_apgi_system_{ids['date_released'][:4]}"
    return "\n".join(
        [
            BEGIN,
            "| Identifier | Value |",
            "|------------|-------|",
            f"| DOI | [{ids['doi']}](https://doi.org/{ids['doi']}) |",
            f"| Author ORCID | [{author['orcid']}](https://orcid.org/{author['orcid']}) |",
            f"| Repository | <{ids['repository']}> |",
            f"| Version | {ids['version']} (released {ids['date_released']}) |",
            "",
            "```bibtex",
            f"@software{{{key},",
            f"  title={{{ids['title']}}},",
            f"  author={{{author['family_names']}, {author['given_names']}}},",
            f"  year={{{ids['date_released'][:4]}}},",
            f"  version={{{ids['version']}}},",
            f"  doi={{{ids['doi']}}},",
            f"  url={{{ids['repository']}}},",
            f"  orcid={{https://orcid.org/{author['orcid']}}}",
            "}",
            "```",
            END,
        ]
    )


def readme_block(text: str) -> Optional[str]:
    start, end = text.find(BEGIN), text.find(END)
    if start < 0 or end < start:
        return None
    return text[start : end + len(END)]


def apply_readme(text: str, ids: Dict[str, Any]) -> str:
    block = render_readme_block(ids)
    if readme_block(text) is None:
        raise ValueError("README.md has no identifiers block markers")
    start, end = text.find(BEGIN), text.find(END)
    return text[:start] + block + text[end + len(END) :]


# -- CITATION.cff ------------------------------------------------------------
def expected_cff_fields(ids: Dict[str, Any]) -> Dict[str, Any]:
    return {
        "doi": ids["doi"],
        "url": f"https://doi.org/{ids['doi']}",
        "version": ids["version"],
        "date-released": ids["date_released"],
        "repository-code": ids["repository"],
    }


def cff_problems(text: str, ids: Dict[str, Any]) -> List[str]:
    data = yaml.safe_load(text)
    problems: List[str] = []
    for key, want in expected_cff_fields(ids).items():
        got = str(data.get(key)) if data.get(key) is not None else None
        if got != want:
            problems.append(f"{key}: expected {want!r}, found {got!r}")
    author = ids["author"]
    orcid_url = f"https://orcid.org/{author['orcid']}"
    people = [(data.get("authors") or [])[:1]]
    for ref in data.get("references") or []:
        if isinstance(ref, dict) and ref.get("authors"):
            people.append(ref["authors"][:1])
    for group in people:
        for person in group:
            if person.get("orcid") != orcid_url:
                problems.append(
                    f"author orcid: expected {orcid_url!r}, found {person.get('orcid')!r}"
                )
            if person.get("family-names") != author["family_names"]:
                problems.append(f"author family-names: found {person.get('family-names')!r}")
    return problems


def apply_cff(text: str, ids: Dict[str, Any]) -> str:
    """Rewrite identifier-bearing lines in place, preserving everything else."""
    for key, want in expected_cff_fields(ids).items():
        quoted = key in {"url", "repository-code", "date-released", "version"}
        value = f'"{want}"' if quoted else want
        text = re.sub(rf"(?m)^{re.escape(key)}:.*$", f"{key}: {value}", text, count=1)
    orcid_url = f"https://orcid.org/{ids['author']['orcid']}"
    return re.sub(r"(?m)^(\s*orcid:\s*).*$", rf'\g<1>"{orcid_url}"', text)


# -- repo-wide scan ----------------------------------------------------------
def tracked_files(root: Path) -> List[Path]:
    try:
        out = subprocess.run(
            ["git", "ls-files", "-z"], cwd=root, capture_output=True, check=True
        ).stdout.decode()
        names = [n for n in out.split("\0") if n]
    except (OSError, subprocess.CalledProcessError):
        names = [str(p.relative_to(root)) for p in root.rglob("*") if p.is_file()]
    return [root / n for n in names]


def scan_text(rel: str, text: str, ids: Dict[str, Any]) -> List[Finding]:
    findings: List[Finding] = []
    canonical_repo = ids["repository"].split("github.com/")[1]
    allowed_repos = {canonical_repo} | {
        r.split("github.com/")[1] for r in ids["related_repositories"]
    }
    for lineno, line in enumerate(text.splitlines(), 1):
        for m in DOI_RE.finditer(line):
            if m.group(0) != ids["doi"] and m.group(0) not in ids["example_dois"]:
                findings.append(Finding(rel, lineno, f"DOI {m.group(0)} differs from {ids['doi']}"))
        # 16-digit groups also match card numbers, so only lines that talk about ORCID count
        for m in ORCID_RE.finditer(line if "orcid" in line.lower() else ""):
            if m.group(0) != ids["author"]["orcid"]:
                findings.append(
                    Finding(
                        rel, lineno, f"ORCID {m.group(0)} differs from {ids['author']['orcid']}"
                    )
                )
        for m in REPO_RE.finditer(line):
            owner, repo = m.group(1), m.group(2).removesuffix(".git").rstrip(".")
            if owner in ids["placeholder_orgs"] or f"{owner}/{repo}" in allowed_repos:
                continue
            findings.append(
                Finding(
                    rel, lineno, f"repository github.com/{owner}/{repo} is not {canonical_repo}"
                )
            )
    return findings


def scan_repo(root: Path, ids: Dict[str, Any]) -> List[Finding]:
    findings: List[Finding] = []
    excluded = tuple(ids.get("scan_exclude", []))
    for path in tracked_files(root):
        rel = path.relative_to(root).as_posix()
        if rel.startswith(excluded) or path.suffix.lower() not in TEXT_SUFFIXES:
            continue
        try:
            if not path.is_file() or path.stat().st_size > MAX_BYTES:
                continue
            text = path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        findings.extend(scan_text(rel, text, ids))
    return findings


def check(root: Path = ROOT) -> List[Finding]:
    ids = load_identifiers(root)
    findings: List[Finding] = []
    readme = (root / "README.md").read_text(encoding="utf-8")
    current = readme_block(readme)
    if current is None:
        findings.append(Finding("README.md", 1, "identifiers block markers are missing"))
    elif current != render_readme_block(ids):
        line = readme[: readme.find(BEGIN)].count("\n") + 1
        findings.append(Finding("README.md", line, "identifiers block is out of date; run --write"))
    for problem in cff_problems((root / "CITATION.cff").read_text(encoding="utf-8"), ids):
        findings.append(Finding("CITATION.cff", 1, problem))
    findings.extend(scan_repo(root, ids))
    return findings


def write(root: Path = ROOT) -> List[str]:
    ids = load_identifiers(root)
    changed: List[str] = []
    for name, fn in (("README.md", apply_readme), ("CITATION.cff", apply_cff)):
        path = root / name
        old = path.read_text(encoding="utf-8")
        new = fn(old, ids)
        if new != old:
            path.write_text(new, encoding="utf-8")
            changed.append(name)
    return changed


def main(argv: Optional[Iterable[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument(
        "--write", action="store_true", help="regenerate README block and CITATION.cff fields"
    )
    mode.add_argument(
        "--check", action="store_true", help="verify sync and scan for divergence (default)"
    )
    args = parser.parse_args(list(argv) if argv is not None else None)
    if args.write:
        changed = write()
        print("updated: " + ", ".join(changed) if changed else "already in sync")
        return 0
    findings = check()
    for f in findings:
        print(f, file=sys.stderr)
    if findings:
        print(
            f"\n{len(findings)} identifier problem(s). Fix the source or run --write.",
            file=sys.stderr,
        )
        return 1
    print("identifiers consistent")
    return 0


if __name__ == "__main__":
    sys.exit(main())
