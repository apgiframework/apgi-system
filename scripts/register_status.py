#!/usr/bin/env python3
"""Check docs/register-evidence.json and render docs/REGISTER-STATUS.md from it.

Every register ID maps to a status and to repository paths that must exist. ``--check`` fails
if an evidence path is missing or the rendered markdown is stale; with no flag it rewrites it.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Dict, List

ROOT = Path(__file__).resolve().parent.parent
SRC, OUT = ROOT / "docs" / "register-evidence.json", ROOT / "docs" / "REGISTER-STATUS.md"
STATUSES = {
    "implemented": "Implemented and tested",
    "implemented-pending-D10": "Implemented; confirm decision D10 (S6-DEC-01)",
    "implemented-reference": "Implemented in this repo; counterpart in apgi-api",
    "implemented-not-enforced": "Implemented; needs repository setting",
    "blocked": "Blocked on a decision or milestone",
}


def load(root: Path = ROOT) -> Dict[str, dict]:
    return json.loads((root / "docs" / "register-evidence.json").read_text(encoding="utf-8"))


def problems(data: Dict[str, dict], root: Path = ROOT) -> List[str]:
    out: List[str] = []
    for key, item in data.items():
        if item["status"] not in STATUSES:
            out.append(f"{key}: unknown status {item['status']!r}")
        if item["status"] != "blocked" and not item["evidence"]:
            out.append(f"{key}: no evidence listed")
        for path in item["evidence"]:
            if not (root / path).exists():
                out.append(f"{key}: evidence path missing: {path}")
    return out


def render(data: Dict[str, dict]) -> str:
    lines = [
        "# Register status (apgi-system)",
        "",
        "Generated by `scripts/register_status.py` from `register-evidence.json`; do not edit by hand.",
        "A register row is only ticked against the evidence listed here.",
        "",
        "| Register ID | Status | Evidence | Note |",
        "|---|---|---|---|",
    ]
    for key, item in data.items():
        ev = "<br>".join(f"`{p}`" for p in item["evidence"]) or "-"
        lines.append(f"| {key} | {STATUSES[item['status']]} | {ev} | {item['note']} |")
    return "\n".join(lines) + "\n"


def main(argv: List[str]) -> int:
    data = load()
    bad = problems(data)
    if "--check" in argv:
        if OUT.read_text(encoding="utf-8") != render(data):
            bad.append("docs/REGISTER-STATUS.md is stale; run python scripts/register_status.py")
        for b in bad:
            print(b, file=sys.stderr)
        return 1 if bad else 0
    if bad:
        for b in bad:
            print(b, file=sys.stderr)
        return 1
    OUT.write_text(render(data), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(data)} entries)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
